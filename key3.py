def move(char):
    if char in keys:
        temp_distf = []
        target = keys[char]
        t_center = ((target["coords"][0][0] + target["coords"][2][0]) / 2, (target["coords"][0][1] + target["coords"][1][1]) / 2)
        
        for finger in fingers:
            f_data = finger["data"]
